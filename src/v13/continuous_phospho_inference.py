def bh_fdr(p_values: Iterable[float]) -> np.ndarray:
    """Benjamini-Hochberg adjustment with finite-value handling."""

    p = np.asarray(list(p_values), dtype=float)
    out = np.full(p.shape, np.nan, dtype=float)
    finite = np.isfinite(p)
    if not finite.any():
        return out
    values = p[finite]
    order = np.argsort(values)
    ranked = values[order]
    q = ranked * len(ranked) / np.arange(1, len(ranked) + 1)
    q = np.minimum.accumulate(q[::-1])[::-1]
    restored = np.empty_like(q)
    restored[order] = np.clip(q, 0.0, 1.0)
    out[finite] = restored
    return out


def _as_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"1", "true", "t", "yes", "y"}


def _resolve_input_path(value: str | Path, config_path: Path) -> Path:
    path = Path(value)
    if path.is_absolute():
        return path
    cwd_path = (REPO_ROOT / path).resolve()
    if cwd_path.exists():
        return cwd_path
    return (config_path.parent / path).resolve()


def load_analysis_config(path: str | Path = DEFAULT_CONFIG) -> dict[str, Any]:
    """Load and minimally validate the production nested config."""

    path = Path(path)
    cfg = yaml.safe_load(path.read_text()) or {}
    required = {
        "analysis",
        "input",
        "contrast",
        "normalization",
        "site_filter",
        "site_model",
        "gene_score",
        "permutation",
        "set_test",
        "canonical_exclusions",
        "comparator_sets",
        "robustness",
    }
    missing = required - set(cfg)
    if missing:
        raise ValueError(f"{path} is missing required sections: {sorted(missing)}")
    if not cfg["site_filter"].get("label_blind", False):
        raise ValueError("The site filter must be declared label_blind")
    if not cfg["site_model"].get("p_value_not_used_for_primary_membership", False):
        raise ValueError("Config must prohibit p-value-defined primary membership")
    if cfg["gene_score"].get("primary") != PRIMARY_SCORE:
        raise ValueError(
            f"Unsupported frozen primary gene score: {cfg['gene_score'].get('primary')!r}"
        )
    return cfg


def build_analysis_profiles(
    cfg: Mapping[str, Any],
    *,
    include_sensitivities: bool = True,
) -> list[AnalysisProfile]:
    """Translate the frozen nested config into executable site profiles."""

    site = cfg["site_filter"]
    normalization = str(cfg["normalization"]["primary"])
    primary_center = normalization.endswith("channel_median_centered")
    primary_source = (
        "official_scaled"
        if "official_scaled_signal" in normalization
        else "signal_to_noise_sum"
    )
    primary = AnalysisProfile(
        name="primary",
        min_localization_score=float(site["min_localization_score_primary"]),
        include_composite=bool(site["include_composite_primary"]),
        require_singly_modified=bool(site["require_singly_modified_primary"]),
        min_finite_total=int(site["min_finite_total"]),
        min_finite_per_plex=int(site["min_finite_per_plex"]),
        deduplication=str(site["deduplication_primary"]),
        channel_center=primary_center,
        signal_source=primary_source,
        exclude_broad_genes=False,
    )
    profiles = [primary]
    if not include_sensitivities:
        return profiles

    if site.get("min_localization_score_sensitivity") is not None:
        profiles.append(
            AnalysisProfile(
                **{
                    **asdict(primary),
                    "name": "localization_score_13",
                    "min_localization_score": float(
                        site["min_localization_score_sensitivity"]
                    ),
                }
            )
        )
    if site.get("site_position_collapse_sensitivity", False):
        profiles.append(
            AnalysisProfile(
                **{
                    **asdict(primary),
                    "name": "site_position_collapse",
                    "deduplication": "accession_site_position",
                }
            )
        )
    if site.get("deduplicated_multimodified_sensitivity", False):
        profiles.append(
            AnalysisProfile(
                **{
                    **asdict(primary),
                    "name": "deduplicated_multimodified",
                    "include_composite": True,
                    "require_singly_modified": False,
                    "deduplication": "accession_modified_peptide_phosphoform",
                }
            )
        )
    if cfg.get("robustness", {}).get(
        "non_distal_or_broad_expression_exclusion_diagnostic", False
    ):
        profiles.append(
            AnalysisProfile(
                **{
                    **asdict(primary),
                    "name": "exclude_non_distal_or_broad_expression",
                    "exclude_broad_genes": True,
                    "broad_expression_flag_column": (
                        "non_distal_specific_or_broad"
                    ),
                }
            )
        )
    if cfg.get("robustness", {}).get("broad_expression_exclusion", False):
        profiles.append(
            AnalysisProfile(
                **{
                    **asdict(primary),
                    "name": "exclude_multicompartment_broad_expression",
                    "exclude_broad_genes": True,
                    "broad_expression_flag_column": "broadly_expressed",
                }
            )
        )
    if "log2_official_scaled_signal_uncentered" in cfg["normalization"].get(
        "sensitivities", []
    ):
        profiles.append(
            AnalysisProfile(
                **{
                    **asdict(primary),
                    "name": "official_scaled_uncentered",
                    "channel_center": False,
                    "signal_source": "official_scaled",
                }
            )
        )
    if "log2_signal_to_noise_sum_channel_median_centered" in cfg[
        "normalization"
    ].get("sensitivities", []):
        profiles.append(
            AnalysisProfile(
                **{
                    **asdict(primary),
                    "name": "signal_to_noise_sum_centered",
                    "channel_center": True,
                    "signal_source": "signal_to_noise_sum",
                }
            )
        )
    if cfg.get("robustness", {}).get("parent_protein_subtraction_secondary", False):
        profiles.append(
            AnalysisProfile(
                **{
                    **asdict(primary),
                    "name": "parent_protein_subtracted",
                    "parent_protein_subtraction": True,
                }
            )
        )
    # Preserve order while preventing identical profiles from running twice.
    unique: dict[tuple[Any, ...], AnalysisProfile] = {}
    for profile in profiles:
        key = tuple(asdict(profile).values())
        unique[key] = profile
    return list(unique.values())


def _normalise_accession(value: Any) -> str:
    text = str(value).strip()
    if not text or text.lower() == "nan":
        return ""
    first = text.split(";", 1)[0].split(",", 1)[0].strip()
    fields = first.split("|")
    if len(fields) >= 2 and fields[0] in {"sp", "tr"}:
        return fields[1].strip()
    return first


def _normalise_sequence(value: Any) -> str:
    text = str(value).upper().strip()
    if not text or text == "NAN":
        return ""
    return "".join(text.split())


def _position_token(value: Any) -> str:
    text = str(value).strip()
    if not text or text.lower() == "nan":
        return ""
    if ";" in text or "," in text:
        return ""
    try:
        number = float(text)
    except ValueError:
        return ""
    return str(int(number)) if number.is_integer() else ""


def _minimum_localization_score(value: Any) -> float:
    """Parse a single or composite localization score conservatively.

    Composite workbook rows store one score per component as a semicolon-
    delimited string.  Requiring the minimum component score to pass prevents
    a well-localized component from masking a poorly localized one.
    """

    if value is None:
        return np.nan
    text = str(value).strip()
    if not text or text.lower() == "nan":
        return np.nan
    parsed: list[float] = []
    for token in re.split(r"[;,|]", text):
        try:
            number = float(token.strip())
        except ValueError:
            continue
        if np.isfinite(number):
            parsed.append(number)
    return float(min(parsed)) if parsed else np.nan


def _residue_from_motif(value: Any) -> str:
    motif = str(value).strip().upper()
    if not motif or motif == "NAN":
        return "?"
    centre = motif[len(motif) // 2]
    return centre if centre in {"S", "T", "Y"} else "?"


def _extract_raw_table(
    workbook: Path,
    sheets: Sequence[str],
    *,
    signal_source: str,
) -> tuple[pd.DataFrame, np.ndarray, pd.DataFrame]:
    """Read requested OSD-462 phosphosite sheets before filtering."""

    sheet_specs = {
        "siteQuant_360": {
            "gene": "gene_symbol",
            "position": "Site Position",
            "accession": "Protein Id",
            "motif": "Motif",
            "localization": "Max Score",
            "sequence": "sequence",
            "redundancy": "redundancy",
            "kind": "single",
        },
        "siteQuant_360_compositeSite": {
            "gene": "geneSymbol",
            "position": "sitePosStr",
            "accession": "proteinID",
            "motif": "motifPeptideStr",
            "localization": "maxScoreStr",
            "sequence": "sequence",
            "redundancy": "redundancyStr",
            "kind": "composite",
        },
    }
    all_meta: list[pd.DataFrame] = []
    all_values: list[np.ndarray] = []
    sample_meta: pd.DataFrame | None = None
    for sheet in sheets:
        if sheet not in sheet_specs:
            raise ValueError(f"Unsupported OSD-462 phosphosite sheet: {sheet!r}")
        spec = sheet_specs[sheet]
        extra = [
            spec["position"],
            spec["motif"],
            spec["localization"],
            spec["sequence"],
            spec["redundancy"],
        ]
        if signal_source == "official_scaled":
            tab = parse_tmt_sheet(
                workbook,
                sheet,
                gene_col=spec["gene"],
                peptide_cols={
                    PLEX1: f"{PLEX1}~num_quant",
                    PLEX2: f"{PLEX2}~num_quant",
                },
                id_col=spec["accession"],
                extra_meta_cols=extra,
            )
        elif signal_source == "signal_to_noise_sum":
            tab = _parse_summed_signal_sheet(
                workbook,
                sheet=sheet,
                gene_col=spec["gene"],
                peptide_cols={
                    PLEX1: f"{PLEX1}~num_quant",
                    PLEX2: f"{PLEX2}~num_quant",
                },
                id_col=spec["accession"],
                extra_meta_cols=extra,
            )
        else:
            raise ValueError(f"Unsupported signal source: {signal_source!r}")
        current_samples = tab.channels[
            tab.channels["condition"].isin(["FL", "GC"])
        ][["column", "plex", "condition", "sample"]].reset_index(drop=True)
        current_samples = current_samples.rename(
            columns={"sample": "sample_id", "condition": "observed_condition"}
        )
        if sample_meta is None:
            sample_meta = current_samples
        elif not current_samples.equals(sample_meta):
            raise ValueError(f"FL/GC channel layout differs in sheet {sheet!r}")

        cols = current_samples["column"].tolist()
        raw = tab.scaled[cols].to_numpy(dtype=float)
        raw = np.where(raw > 0, raw, np.nan)
        meta = tab.meta.copy().rename(
            columns={
                spec["position"]: "site_position",
                spec["motif"]: "motif",
                spec["localization"]: "localization_score_raw",
                spec["sequence"]: "modified_sequence",
                spec["redundancy"]: "localization_redundancy",
            }
        )
        meta["source_sheet"] = sheet
        meta["site_kind"] = spec["kind"]
        meta["source_row"] = np.arange(len(meta), dtype=int) + 4
        all_meta.append(meta)
        all_values.append(raw)
    if sample_meta is None:
        raise ValueError("No phosphosite sheets were loaded")
    return (
        pd.concat(all_meta, ignore_index=True),
        np.vstack(all_values),
        sample_meta,
    )


def _parse_summed_signal_sheet(
    path: Path,
    *,
    sheet: str,
    gene_col: str,
    peptide_cols: Mapping[str, str],
    id_col: str,
    extra_meta_cols: Sequence[str],
) -> TmtTable:
    """Parse the workbook's unscaled summed signal-to-noise channels.

    The shared historical parser intentionally exposes only official scaled
    channels.  This local reader keeps the new normalization sensitivity
    isolated from that established API.
    """

    import openpyxl

    workbook = openpyxl.load_workbook(path, read_only=True, data_only=True)
    worksheet = workbook[sheet]
    iterator = worksheet.iter_rows(values_only=True)
    _ = next(iterator)
    sample_labels = next(iterator)
    headers = next(iterator)
    header_index = {
        str(value).strip(): i
        for i, value in enumerate(headers)
        if isinstance(value, str)
    }
    required = [gene_col, id_col, *peptide_cols.values(), *extra_meta_cols]
    missing = [name for name in required if name not in header_index]
    if missing:
        workbook.close()
        raise KeyError(f"{sheet!r} lacks summed-signal metadata columns: {missing}")

    channels: list[dict[str, Any]] = []
    for i, header in enumerate(headers):
        if not isinstance(header, str) or "~" not in header:
            continue
        low = header.lower()
        if "scaled" in low or "_sn_sum" not in low:
            continue
        plex = header.split("~", 1)[0].strip()
        if plex not in {PLEX1, PLEX2}:
            continue
        sample = sample_labels[i] if i < len(sample_labels) else None
        if not isinstance(sample, str) or "-" not in sample:
            continue
        condition = sample.split("-", 1)[0].strip().upper()
        if condition not in {"BL", "FL", "GC"}:
            continue
        column = f"{plex}|{condition}|{sample.strip()}"
        channels.append(
            {
                "idx": i,
                "column": column,
                "plex": plex,
                "value_type": "sum",
                "condition": condition,
                "sample": sample.strip(),
            }
        )
    if not channels:
        workbook.close()
        raise ValueError(f"No summed signal-to-noise channels found in {sheet!r}")

    meta_rows: list[dict[str, Any]] = []
    value_rows: list[list[float]] = []
    for row in iterator:
        gene = row[header_index[gene_col]]
        if gene is None or str(gene).strip() == "":
            continue
        record: dict[str, Any] = {
            "gene_symbol": str(gene).strip(),
            "protein_id": row[header_index[id_col]],
        }
        for plex, column in peptide_cols.items():
            record[f"n_pep_{plex}"] = pd.to_numeric(
                row[header_index[column]], errors="coerce"
            )
        for column in extra_meta_cols:
            record[column] = row[header_index[column]]
        meta_rows.append(record)
        value_rows.append(
            [
                pd.to_numeric(row[channel["idx"]], errors="coerce")
                for channel in channels
            ]
        )
    workbook.close()
    channel_table = pd.DataFrame(channels).drop(columns="idx")
    return TmtTable(
        meta=pd.DataFrame(meta_rows),
        scaled=pd.DataFrame(
            value_rows, columns=channel_table["column"].tolist()
        ),
        channels=channel_table,
        sheet=sheet,
    )


def load_parent_protein_values(
    workbook: str | Path,
    sample_metadata: pd.DataFrame,
    genes: Sequence[str],
    *,
    channel_center: bool = True,
) -> np.ndarray:
    """Return gene-level protein log2 values aligned to phosphosite samples.

    Multiple protein rows for a symbol are collapsed independently in each
    sample using quantified-peptide weights.  Missing parent proteins remain
    missing and therefore cannot enter the protein-subtracted sensitivity.
    """

    tab = parse_tmt_sheet(
        workbook,
        "protein_quant_2721",
        gene_col="Gene Symbol",
        peptide_cols={
            PLEX1: f"{PLEX1} Peptides",
            PLEX2: f"{PLEX2} Peptides",
        },
        id_col="Protein Id",
    )
    current = tab.channels[
        tab.channels["condition"].isin(["FL", "GC"])
    ][["column", "plex", "condition", "sample"]].reset_index(drop=True)
    current = current.rename(
        columns={"sample": "sample_id", "condition": "observed_condition"}
    )
    expected_keys = list(
        zip(
            sample_metadata["plex"],
            sample_metadata["observed_condition"],
            sample_metadata["sample_id"],
        )
    )
    current_lookup = {
        (row.plex, row.observed_condition, row.sample_id): row.column
        for row in current.itertuples(index=False)
    }
    missing_keys = [key for key in expected_keys if key not in current_lookup]
    if missing_keys:
        raise ValueError(
            "Protein and phosphosite sample layouts do not align; missing "
            f"protein channels for {missing_keys}"
        )
    columns = [current_lookup[key] for key in expected_keys]
    raw = tab.scaled[columns].to_numpy(dtype=float)
    raw = np.where(raw > 0, raw, np.nan)
    protein_sample_meta = sample_metadata.copy()
    protein_sample_meta["column"] = columns
    values, _ = _log2_normalise(
        raw, protein_sample_meta, channel_center=channel_center
    )
    meta = tab.meta.copy()
    plex_weights = {
        plex: np.where(
            (
                numeric := pd.to_numeric(
                    meta.get(f"n_pep_{plex}"), errors="coerce"
                ).fillna(0).to_numpy(dtype=float)
            )
            > 0,
            numeric,
            1.0,
        )
        for plex in (PLEX1, PLEX2)
    }
    weights = np.column_stack(
        [
            plex_weights[str(plex)]
            for plex in protein_sample_meta["plex"]
        ]
    )
    gene_to_rows = meta.groupby(meta["gene_symbol"].astype(str), sort=False).indices
    output = np.full((len(genes), len(sample_metadata)), np.nan, dtype=float)
    for i, gene in enumerate(map(str, genes)):
        idx_value = gene_to_rows.get(gene)
        if idx_value is None:
            continue
        idx = np.asarray(idx_value, dtype=int)
        block = values[idx]
        block_weights = weights[idx] * np.isfinite(block)
        numerator = np.nansum(block * block_weights, axis=0)
        denominator = block_weights.sum(axis=0)
        output[i] = np.divide(
            numerator,
            denominator,
            out=np.full(len(sample_metadata), np.nan),
            where=denominator > 0,
        )
    return output


def normalization_equivalence_audit(
    workbook: str | Path,
    sheets: Sequence[str],
    output_dir: str | Path,
    *,
    min_per_group: int = 3,
) -> dict[str, Any]:
    """Audit whether official scaled and summed S/N encode the same contrast.

    GeneLab's official scaled values are row/plex rescalings of summed S/N
    values.  A constant within-row/plex ratio cancels from an uncentered log2
    FL-GC contrast, making the two inputs algebraically redundant rather than
    independent robustness evidence.
    """

    workbook = Path(workbook)
    output_dir = Path(output_dir)
    rows: list[pd.DataFrame] = []
    contrast_rows: list[pd.DataFrame] = []
    sheet_specs = {
        "siteQuant_360": (
            "gene_symbol",
            "Site Position",
            "Protein Id",
            ["Site Position", "Motif", "Max Score", "redundancy", "sequence"],
        ),
        "siteQuant_360_compositeSite": (
            "geneSymbol",
            "sitePosStr",
            "proteinID",
            [
                "sitePosStr",
                "motifPeptideStr",
                "maxScoreStr",
                "redundancyStr",
                "sequence",
            ],
        ),
    }
    for sheet in sheets:
        gene_col, position_col, accession_col, extra = sheet_specs[sheet]
        scaled = parse_tmt_sheet(
            workbook,
            sheet,
            gene_col=gene_col,
            peptide_cols={
                PLEX1: f"{PLEX1}~num_quant",
                PLEX2: f"{PLEX2}~num_quant",
            },
            id_col=accession_col,
            extra_meta_cols=extra,
        )
        summed = _parse_summed_signal_sheet(
            workbook,
            sheet=sheet,
            gene_col=gene_col,
            peptide_cols={
                PLEX1: f"{PLEX1}~num_quant",
                PLEX2: f"{PLEX2}~num_quant",
            },
            id_col=accession_col,
            extra_meta_cols=extra,
        )
        if len(scaled.meta) != len(summed.meta):
            raise ValueError(f"Scaled/summed row count differs in {sheet!r}")
        scaled_lookup = {
            (row.plex, row.condition, row.sample): row.column
            for row in scaled.channels.itertuples(index=False)
        }
        summed_lookup = {
            (row.plex, row.condition, row.sample): row.column
            for row in summed.channels.itertuples(index=False)
        }
        keys = [
            key
            for key in scaled_lookup
            if key in summed_lookup
        ]
        if len(keys) != len(scaled_lookup) or len(keys) != len(summed_lookup):
            raise ValueError(f"Scaled/summed channels do not align in {sheet!r}")
        scaled_values = scaled.scaled[
            [scaled_lookup[key] for key in keys]
        ].to_numpy(dtype=float)
        summed_values = summed.scaled[
            [summed_lookup[key] for key in keys]
        ].to_numpy(dtype=float)
        valid_ratio = (
            np.isfinite(scaled_values)
            & np.isfinite(summed_values)
            & (summed_values > 0)
        )
        ratio = np.divide(
            scaled_values,
            summed_values,
            out=np.full_like(scaled_values, np.nan),
            where=valid_ratio,
        )
        row_meta = scaled.meta.copy().rename(
            columns={position_col: "site_position"}
        )
        row_meta["source_sheet"] = sheet
        row_meta["source_row"] = np.arange(len(row_meta)) + 4
        for plex in (PLEX1, PLEX2):
            idx = np.asarray(
                [i for i, key in enumerate(keys) if key[0] == plex],
                dtype=int,
            )
            part = ratio[:, idx]
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", category=RuntimeWarning)
                mean = np.nanmean(part, axis=1)
                sd = np.nanstd(part, axis=1, ddof=0)
            cv = np.divide(
                sd,
                np.abs(mean),
                out=np.full_like(mean, np.nan),
                where=np.abs(mean) > 0,
            )
            rows.append(
                pd.DataFrame(
                    {
                        "source_sheet": sheet,
                        "source_row": row_meta["source_row"],
                        "gene_symbol": row_meta["gene_symbol"],
                        "site_position": row_meta["site_position"],
                        "plex": plex,
                        "n_ratio_channels": np.isfinite(part).sum(axis=1),
                        "scaled_to_summed_ratio_mean": mean,
                        "scaled_to_summed_ratio_cv": cv,
                    }
                )
            )

        fg_keys = [key for key in keys if key[1] in {"FL", "GC"}]
        fg_idx = np.asarray([keys.index(key) for key in fg_keys], dtype=int)
        sample_meta = pd.DataFrame(
            {
                "column": [scaled_lookup[key] for key in fg_keys],
                "plex": [key[0] for key in fg_keys],
                "observed_condition": [key[1] for key in fg_keys],
                "sample_id": [key[2] for key in fg_keys],
            }
        )
        observed = (
            sample_meta["observed_condition"].eq("FL").to_numpy()[None, :]
        )
        scaled_fg = np.where(
            scaled_values[:, fg_idx] > 0,
            scaled_values[:, fg_idx],
            np.nan,
        )
        summed_fg = np.where(
            summed_values[:, fg_idx] > 0,
            summed_values[:, fg_idx],
            np.nan,
        )
        scaled_log = np.log2(scaled_fg)
        summed_log = np.log2(summed_fg)
        scaled_uncentered = site_contrasts(
            scaled_log, sample_meta, observed, min_per_group=min_per_group
        )[0]
        summed_uncentered = site_contrasts(
            summed_log, sample_meta, observed, min_per_group=min_per_group
        )[0]
        scaled_centered, _ = _log2_normalise(
            scaled_fg, sample_meta, channel_center=True
        )
        summed_centered, _ = _log2_normalise(
            summed_fg, sample_meta, channel_center=True
        )
        scaled_centered_effect = site_contrasts(
            scaled_centered, sample_meta, observed, min_per_group=min_per_group
        )[0]
        summed_centered_effect = site_contrasts(
            summed_centered, sample_meta, observed, min_per_group=min_per_group
        )[0]
        contrast_rows.append(
            pd.DataFrame(
                {
                    "source_sheet": sheet,
                    "source_row": row_meta["source_row"],
                    "gene_symbol": row_meta["gene_symbol"],
                    "site_position": row_meta["site_position"],
                    "scaled_uncentered_effect": scaled_uncentered,
                    "summed_uncentered_effect": summed_uncentered,
                    "abs_difference_uncentered": np.abs(
                        scaled_uncentered - summed_uncentered
                    ),
                    "scaled_channel_centered_effect": scaled_centered_effect,
                    "summed_channel_centered_effect": summed_centered_effect,
                    "abs_difference_channel_centered": np.abs(
                        scaled_centered_effect - summed_centered_effect
                    ),
                }
            )
        )
    ratio_table = pd.concat(rows, ignore_index=True)
    contrast_table = pd.concat(contrast_rows, ignore_index=True)
    ratio_table.to_csv(
        output_dir / "normalization_scaled_to_summed_ratio_audit.tsv",
        sep="\t",
        index=False,
    )
    contrast_table.to_csv(
        output_dir / "normalization_contrast_equivalence_audit.tsv",
        sep="\t",
        index=False,
    )
    finite_cv = pd.to_numeric(
        ratio_table["scaled_to_summed_ratio_cv"], errors="coerce"
    ).dropna()
    uncentered_diff = pd.to_numeric(
        contrast_table["abs_difference_uncentered"], errors="coerce"
    ).dropna()
    centered_diff = pd.to_numeric(
        contrast_table["abs_difference_channel_centered"], errors="coerce"
    ).dropna()
    summary = {
        "n_row_plex_ratios": int(len(ratio_table)),
        "max_scaled_to_summed_ratio_cv": (
            float(finite_cv.max()) if len(finite_cv) else None
        ),
        "median_scaled_to_summed_ratio_cv": (
            float(finite_cv.median()) if len(finite_cv) else None
        ),
        "max_abs_uncentered_FL_minus_GC_contrast_difference": (
            float(uncentered_diff.max()) if len(uncentered_diff) else None
        ),
        "max_abs_channel_centered_FL_minus_GC_contrast_difference": (
            float(centered_diff.max()) if len(centered_diff) else None
        ),
        "independent_robustness_evidence": False,
        "interpretation": (
            "Scaled-versus-summed S/N is an algebraic normalization audit, "
            "not independent evidence. Neither input resolves condition-to-"
            "reporter-tag aliasing."
        ),
    }
    (output_dir / "normalization_equivalence_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n"
    )
    return summary


def _log2_normalise(
    raw_values: np.ndarray,
    sample_meta: pd.DataFrame,
    *,
    channel_center: bool,
) -> tuple[np.ndarray, np.ndarray]:
    """Log2-transform and optionally median-center channels within plex."""

    log2 = np.log2(np.asarray(raw_values, dtype=float))
    uncentered_mean = np.nanmean(log2, axis=1)
    if channel_center:
        for _, indexes in sample_meta.groupby("plex", sort=False).groups.items():
            idx = np.asarray(list(indexes), dtype=int)
            centres = np.nanmedian(log2[:, idx], axis=0)
            log2[:, idx] = log2[:, idx] - centres[None, :]
    return log2, uncentered_mean


def _site_key(meta: pd.DataFrame, deduplication: str) -> pd.Series:
    accession = meta["protein_accession"].astype(str)
    if deduplication == "accession_modified_peptide_phosphoform":
        sequence = meta["modified_sequence_normalized"].astype(str)
        fallback = (
            accession
            + "|"
            + meta["site_residue"].astype(str)
            + meta["site_position_token"].astype(str)
        )
        return pd.Series(
            np.where(sequence.ne(""), accession + "|" + sequence, fallback),
            index=meta.index,
        )
    if deduplication == "accession_site_position":
        return (
            accession
            + "|"
            + meta["site_residue"].astype(str)
            + meta["site_position_token"].astype(str)
        )
    raise ValueError(f"Unsupported site de-duplication mode: {deduplication!r}")


def _deduplicate(
    meta: pd.DataFrame,
    values: np.ndarray,
) -> tuple[pd.DataFrame, np.ndarray]:
    """Collapse duplicate analytical features by per-sample median."""

    groups = meta.groupby("canonical_site_key", sort=True).indices
    # The production OSD-462 single-site universes currently contain no
    # duplicate canonical keys. Avoid thousands of one-row pandas reductions
    # in that common case; this is an exact fast path, not a change to the
    # de-duplication rule.
    if len(groups) == len(meta):
        positioned = meta.assign(_source_position=np.arange(len(meta))).sort_values(
            "canonical_site_key", kind="stable"
        )
        order = positioned["_source_position"].to_numpy(dtype=int)
        out_meta = positioned.drop(columns="_source_position").reset_index(drop=True)
        out_meta["n_source_rows_collapsed"] = 1
        out_meta["source_rows"] = out_meta["raw_feature_id"].astype(str)
        return out_meta, values[order].copy()

    rows: list[pd.Series] = []
    matrices: list[np.ndarray] = []
    for key, idx_value in groups.items():
        idx = np.asarray(idx_value, dtype=int)
        part = meta.iloc[idx]
        row = part.iloc[0].copy()
        row["canonical_site_key"] = key
        row["n_source_rows_collapsed"] = int(len(idx))
        row["source_rows"] = ";".join(part["raw_feature_id"].astype(str))
        row["localization_score"] = pd.to_numeric(
            part["localization_score"], errors="coerce"
        ).min()
        row["mean_log2_signal_uncentered"] = pd.to_numeric(
            part["mean_log2_signal_uncentered"], errors="coerce"
        ).median()
        rows.append(row)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", category=RuntimeWarning)
            matrices.append(np.nanmedian(values[idx], axis=0))
    out_meta = pd.DataFrame(rows).reset_index(drop=True)
    out_values = np.vstack(matrices) if matrices else np.empty((0, values.shape[1]))
    return out_meta, out_values


def prepare_osd462_phosphosites(
    workbook: str | Path,
    profile: AnalysisProfile,
    *,
    primary_sheets: Sequence[str] = ("siteQuant_360",),
    broad_genes: set[str] | None = None,
    raw_input: tuple[pd.DataFrame, np.ndarray, pd.DataFrame] | None = None,
) -> PreparedPhosphoData:
    """Build one label-blind, localization-aware OSD-462 site universe."""

    sheets = list(primary_sheets)
    if profile.include_composite and "siteQuant_360_compositeSite" not in sheets:
        sheets.append("siteQuant_360_compositeSite")
    if raw_input is None:
        meta, raw, sample_meta = _extract_raw_table(
            Path(workbook), sheets, signal_source=profile.signal_source
        )
    else:
        meta, raw, sample_meta = raw_input
        meta = meta.copy()
        raw = raw.copy()
        sample_meta = sample_meta.copy()
    values, uncentered_mean = _log2_normalise(
        raw, sample_meta, channel_center=profile.channel_center
    )

    meta = meta.copy()
    meta["protein_accession"] = meta["protein_id"].map(_normalise_accession)
    meta["modified_sequence_normalized"] = meta["modified_sequence"].map(
        _normalise_sequence
    )
    meta["site_position_token"] = meta["site_position"].map(_position_token)
    meta["site_residue"] = meta["motif"].map(_residue_from_motif)
    meta["localization_score"] = meta["localization_score_raw"].map(
        _minimum_localization_score
    )
    meta["n_phosphorylations_in_feature"] = meta[
        "modified_sequence_normalized"
    ].str.count("#")
    meta["raw_feature_id"] = (
        meta["source_sheet"].astype(str)
        + ":"
        + meta["source_row"].astype(str)
    )
    meta["mean_log2_signal_uncentered"] = uncentered_mean
    finite = np.isfinite(values)
    meta["n_finite_total"] = finite.sum(axis=1)
    for plex, indexes in sample_meta.groupby("plex", sort=False).groups.items():
        idx = np.asarray(list(indexes), dtype=int)
        meta[f"n_finite_{plex}"] = finite[:, idx].sum(axis=1)

    reasons = pd.DataFrame(index=meta.index)
    reasons["missing_gene_symbol"] = (
        meta["gene_symbol"].isna()
        | meta["gene_symbol"].astype(str).str.strip().isin(["", "nan"])
    )
    reasons["composite_or_multi_position"] = (
        meta["site_kind"].ne("single") | meta["site_position_token"].eq("")
    ) & (not profile.include_composite)
    reasons["below_localization_score"] = (
        meta["localization_score"].isna()
        | (meta["localization_score"] < profile.min_localization_score)
    )
    reasons["not_singly_modified"] = (
        meta["n_phosphorylations_in_feature"].ne(1)
        if profile.require_singly_modified
        else False
    )
    reasons["insufficient_total_completeness"] = (
        meta["n_finite_total"] < profile.min_finite_total
    )
    plex_fail = np.zeros(len(meta), dtype=bool)
    for plex in sample_meta["plex"].drop_duplicates():
        plex_fail |= (
            meta[f"n_finite_{plex}"].to_numpy(dtype=int)
            < profile.min_finite_per_plex
        )
    reasons["insufficient_per_plex_completeness"] = plex_fail
    if profile.exclude_broad_genes:
        broad_genes = broad_genes or set()
        reasons["broad_expression_exclusion"] = meta["gene_symbol"].isin(broad_genes)
    else:
        reasons["broad_expression_exclusion"] = False

    keep = ~reasons.any(axis=1)
    audit_rows = [
        {
            "profile": profile.name,
            "stage": "input",
            "reason": "all_rows",
            "n_rows": int(len(meta)),
        }
    ]
    for reason in reasons:
        audit_rows.append(
            {
                "profile": profile.name,
                "stage": "label_blind_filter",
                "reason": reason,
                "n_rows": int(reasons[reason].sum()),
            }
        )
    meta = meta.loc[keep].reset_index(drop=True)
    values = values[keep.to_numpy()]
    meta["canonical_site_key"] = _site_key(meta, profile.deduplication)
    before = len(meta)
    meta, values = _deduplicate(meta, values)
    finite_after_dedup = np.isfinite(values)
    meta["n_finite_total"] = finite_after_dedup.sum(axis=1)
    for plex, indexes in sample_meta.groupby("plex", sort=False).groups.items():
        idx = np.asarray(list(indexes), dtype=int)
        meta[f"n_finite_{plex}"] = finite_after_dedup[:, idx].sum(axis=1)
    audit_rows.extend(
        [
            {
                "profile": profile.name,
                "stage": "deduplication",
                "reason": "rows_before_deduplication",
                "n_rows": int(before),
            },
            {
                "profile": profile.name,
                "stage": "deduplication",
                "reason": "unique_features_after_deduplication",
                "n_rows": int(len(meta)),
            },
            {
                "profile": profile.name,
                "stage": "deduplication",
                "reason": "duplicate_rows_collapsed",
                "n_rows": int(before - len(meta)),
            },
        ]
    )
    meta["missing_fraction"] = 1.0 - (
        np.isfinite(values).sum(axis=1) / values.shape[1]
    )

    for plex, group in sample_meta.groupby("plex", sort=False):
        counts = group["observed_condition"].value_counts()
        if counts.get("FL", 0) != counts.get("GC", 0):
            raise ValueError(
                f"Observed FL/GC labels are not balanced in plex {plex}: "
                f"{counts.to_dict()}"
            )
    return PreparedPhosphoData(
        values=values,
        site_metadata=meta.reset_index(drop=True),
        sample_metadata=sample_meta.reset_index(drop=True),
        filter_audit=pd.DataFrame(audit_rows),
        profile=profile,
    )


def enumerate_balanced_labels(
    sample_metadata: pd.DataFrame,
    *,
    mode: str = "exact",
    n_null: int | None = None,
    seed: int = 20260728,
) -> PermutationDesign:
    """Enumerate or sample balanced label assignments within every plex.

    The observed assignment is always row zero.  In ``exact`` mode, every
    balanced assignment is included exactly once.  In ``sampled`` mode,
    ``n_null`` assignments are sampled without replacement from the remaining
    exact assignment space.
    """

    required = {"plex", "observed_condition"}
    missing = required - set(sample_metadata)
    if missing:
        raise ValueError(f"sample metadata lacks columns: {sorted(missing)}")
    plexes = list(sample_metadata["plex"].drop_duplicates())
    combinations_by_plex: list[list[tuple[int, ...]]] = []
    observed_choice: list[int] = []
    plex_indices: list[np.ndarray] = []
    for plex in plexes:
        idx = np.flatnonzero(sample_metadata["plex"].to_numpy() == plex)
        observed_local = tuple(
            np.flatnonzero(
                sample_metadata.iloc[idx]["observed_condition"].to_numpy() == "FL"
            ).tolist()
        )
        k = len(observed_local)
        if k == 0 or k == len(idx):
            raise ValueError(f"Plex {plex!r} has no within-plex label contrast")
        choices = list(itertools.combinations(range(len(idx)), k))
        combinations_by_plex.append(choices)
        observed_choice.append(choices.index(observed_local))
        plex_indices.append(idx)

    dimensions = [len(x) for x in combinations_by_plex]
    total = int(math.prod(dimensions))
    observed_flat = int(np.ravel_multi_index(tuple(observed_choice), dimensions))
    all_flat = np.arange(total, dtype=int)
    null_flat = all_flat[all_flat != observed_flat]
    if mode == "exact":
        selected = np.concatenate([[observed_flat], null_flat])
    elif mode in {"sampled", "smoke"}:
        if n_null is None or n_null <= 0:
            raise ValueError("sampled permutation mode requires n_null > 0")
        rng = np.random.default_rng(seed)
        n_draw = min(int(n_null), len(null_flat))
        selected_null = rng.choice(null_flat, size=n_draw, replace=False)
        selected = np.concatenate([[observed_flat], selected_null])
    else:
        raise ValueError("permutation mode must be exact, sampled, or smoke")

    labels = np.zeros((len(selected), len(sample_metadata)), dtype=bool)
    unravelled = np.array(np.unravel_index(selected, dimensions)).T
    for b, choice_indices in enumerate(unravelled):
        for p, choice_index in enumerate(choice_indices):
            global_idx = plex_indices[p][
                np.asarray(combinations_by_plex[p][choice_index], dtype=int)
            ]
            labels[b, global_idx] = True
    observed = sample_metadata["observed_condition"].to_numpy() == "FL"
    if not np.array_equal(labels[0], observed):
        raise RuntimeError("Observed balanced assignment was not placed in row zero")
    return PermutationDesign(
        labels=labels,
        permutation_ids=selected,
        observed_row=0,
        mode=mode,
        n_total_possible=total,
        null_rows=np.arange(1, len(selected), dtype=int),
    )


def _iter_chunks(n: int, chunk_size: int) -> Iterator[slice]:
    for start in range(0, n, chunk_size):
        yield slice(start, min(n, start + chunk_size))


def site_contrasts(
    values: np.ndarray,
    sample_metadata: pd.DataFrame,
    labels: np.ndarray,
    *,
    min_per_group: int = 3,
) -> np.ndarray:
    """Equal-weight within-plex FL-GC contrasts for each assignment.

    The result has shape ``assignments x sites``.  Both plex-specific contrasts
    must have at least ``min_per_group`` finite observations in each permuted
    group.  The two valid plex contrasts then receive equal weight.  With
    complete balanced data this equals the flight coefficient from
    ``value ~ flight + plex``; missing data do not silently reweight one plex.
    """

    values = np.asarray(values, dtype=float)
    labels = np.asarray(labels, dtype=bool)
    if values.ndim != 2 or labels.ndim != 2:
        raise ValueError("values and labels must both be two-dimensional")
    if values.shape[1] != labels.shape[1]:
        raise ValueError("values and labels have different sample counts")
    finite = np.isfinite(values)
    zero = np.nan_to_num(values, nan=0.0)
    plex_effects: list[np.ndarray] = []
    for _, indexes in sample_metadata.groupby("plex", sort=False).groups.items():
        idx = np.asarray(list(indexes), dtype=int)
        lp = labels[:, idx].astype(float)
        cp = 1.0 - lp
        y = zero[:, idx]
        m = finite[:, idx].astype(float)
        fl_n = lp @ m.T
        gc_n = cp @ m.T
        fl_sum = lp @ y.T
        gc_sum = cp @ y.T
        with np.errstate(divide="ignore", invalid="ignore"):
            effect = fl_sum / fl_n - gc_sum / gc_n
        effect[(fl_n < min_per_group) | (gc_n < min_per_group)] = np.nan
        plex_effects.append(effect)
    stacked = np.stack(plex_effects, axis=0)
    valid_all_plexes = np.isfinite(stacked).all(axis=0)
    equal_weight = np.mean(stacked, axis=0)
    equal_weight[~valid_all_plexes] = np.nan
    return equal_weight


def build_gene_layout(site_metadata: pd.DataFrame) -> GeneLayout:
    genes = site_metadata["gene_symbol"].astype(str).to_numpy()
    order = np.argsort(genes, kind="stable")
    sorted_genes = genes[order]
    unique, starts, counts = np.unique(
        sorted_genes, return_index=True, return_counts=True
    )
    return GeneLayout(
        genes=unique,
        starts=starts,
        ends=starts + counts,
        site_order=order,
    )


def aggregate_parent_gene_scores(
    site_effects: np.ndarray,
    layout: GeneLayout,
) -> dict[str, np.ndarray]:
    """Collapse signed site effects to one value per parent gene.

    Positive values mean lower phosphorylation in flight.  The primary median
    remains signed.  ``one_sided_maxmean`` is a sparse-hit sensitivity and
    truncates phosphorylation increases at zero.
    """

    suppression = -np.asarray(site_effects, dtype=float)[:, layout.site_order]
    n_perm = suppression.shape[0]
    outputs = {
        name: np.full((n_perm, len(layout.genes)), np.nan, dtype=float)
        for name in SCORE_NAMES
    }
    for gene_index, (start, end) in enumerate(zip(layout.starts, layout.ends)):
        block = suppression[:, start:end]
        finite = np.isfinite(block)
        count = finite.sum(axis=1)
        total = np.nansum(block, axis=1)
        outputs["mean_negative_site_effect"][:, gene_index] = np.divide(
            total,
            count,
            out=np.full(n_perm, np.nan),
            where=count > 0,
        )
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", category=RuntimeWarning)
            outputs[PRIMARY_SCORE][:, gene_index] = np.nanmedian(block, axis=1)
        positive = np.where(finite, np.maximum(block, 0.0), np.nan)
        outputs["one_sided_maxmean"][:, gene_index] = np.divide(
            np.nansum(positive, axis=1),
            count,
            out=np.full(n_perm, np.nan),
            where=count > 0,
        )
    return outputs


def _score_assignment_chunk(
    data: PreparedPhosphoData,
    layout: GeneLayout,
    labels: np.ndarray,
    *,
    min_per_group: int,
    parent_protein_values: np.ndarray | None,
) -> tuple[np.ndarray, dict[str, np.ndarray]]:
    """Compute site effects and parent scores for one permutation chunk."""

    effects = site_contrasts(
        data.values,
        data.sample_metadata,
        labels,
        min_per_group=min_per_group,
    )
    if parent_protein_values is not None:
        if parent_protein_values.shape != (
            len(layout.genes),
            data.values.shape[1],
        ):
            raise ValueError("Parent-protein matrix is not aligned to gene layout")
        protein_effects = site_contrasts(
            parent_protein_values,
            data.sample_metadata,
            labels,
            min_per_group=min_per_group,
        )
        gene_index = pd.Index(layout.genes).get_indexer(
            data.site_metadata["gene_symbol"].astype(str)
        )
        if (gene_index < 0).any():
            raise RuntimeError("Phosphosite gene was absent from its gene layout")
        # Occupancy-style sensitivity: beta_phosphosite - beta_parent_protein.
        effects = effects - protein_effects[:, gene_index]
    return effects, aggregate_parent_gene_scores(effects, layout)


def _first_pass_calibration(
    data: PreparedPhosphoData,
    design: PermutationDesign,
    layout: GeneLayout,
    *,
    chunk_size: int,
    min_per_group: int,
    parent_protein_values: np.ndarray | None = None,
) -> NullCalibration:
    n_genes = len(layout.genes)
    sums = {name: np.zeros(n_genes) for name in SCORE_NAMES}
    squares = {name: np.zeros(n_genes) for name in SCORE_NAMES}
    counts = {name: np.zeros(n_genes, dtype=np.int64) for name in SCORE_NAMES}
    observed_raw = {
        name: np.full(n_genes, np.nan, dtype=float) for name in SCORE_NAMES
    }
    assignment_site_valid_counts = np.zeros(len(design.labels), dtype=np.int64)
    assignment_gene_valid_counts = {
        name: np.zeros(len(design.labels), dtype=np.int64)
        for name in SCORE_NAMES
    }
    site_valid_assignment_counts = np.zeros(data.values.shape[0], dtype=np.int64)
    calibration_rows = (
        np.arange(len(design.labels))
        if design.mode == "exact"
        else design.null_rows
    )
    calibration_mask_all = np.zeros(len(design.labels), dtype=bool)
    calibration_mask_all[calibration_rows] = True

    for slc in _iter_chunks(len(design.labels), chunk_size):
        effects, scores = _score_assignment_chunk(
            data,
            layout,
            design.labels[slc],
            min_per_group=min_per_group,
            parent_protein_values=parent_protein_values,
        )
        assignment_site_valid_counts[slc] = np.isfinite(effects).sum(axis=1)
        site_valid_assignment_counts += np.isfinite(effects).sum(axis=0)
        for name in SCORE_NAMES:
            assignment_gene_valid_counts[name][slc] = np.isfinite(
                scores[name]
            ).sum(axis=1)
        global_rows = np.arange(slc.start, slc.stop)
        if design.observed_row in global_rows:
            local = int(design.observed_row - slc.start)
            for name in SCORE_NAMES:
                observed_raw[name] = scores[name][local].copy()
        local_calibration = calibration_mask_all[global_rows]
        if not local_calibration.any():
            continue
        for name in SCORE_NAMES:
            x = scores[name][local_calibration]
            finite = np.isfinite(x)
            sums[name] += np.nansum(x, axis=0)
            squares[name] += np.nansum(x * x, axis=0)
            counts[name] += finite.sum(axis=0)

    means: dict[str, np.ndarray] = {}
    sds: dict[str, np.ndarray] = {}
    observed_z: dict[str, np.ndarray] = {}
    for name in SCORE_NAMES:
        means[name] = np.divide(
            sums[name],
            counts[name],
            out=np.full(n_genes, np.nan),
            where=counts[name] > 0,
        )
        variance = np.divide(
            squares[name],
            counts[name],
            out=np.full(n_genes, np.nan),
            where=counts[name] > 0,
        ) - means[name] ** 2
        variance = np.maximum(variance, 0.0)
        sds[name] = np.sqrt(variance)
        observed_z[name] = np.divide(
            observed_raw[name] - means[name],
            sds[name],
            out=np.full(n_genes, np.nan),
            where=np.isfinite(sds[name]) & (sds[name] > 0),
        )
    return NullCalibration(
        means=means,
        sds=sds,
        counts=counts,
        observed_raw=observed_raw,
        observed_z=observed_z,
        assignment_site_valid_counts=assignment_site_valid_counts,
        assignment_gene_valid_counts=assignment_gene_valid_counts,
        site_valid_assignment_counts=site_valid_assignment_counts,
    )


def load_frozen_gene_sets(
    path: str | Path,
    cfg: Mapping[str, Any],
) -> tuple[dict[str, set[str]], pd.DataFrame]:
    """Load the frozen long-format reference-builder output.

    Expected columns are ``gene_symbol`` and ``gene_set``.  When present,
    ``final_for_testing`` and ``status`` are enforced.  The literature-frozen
    ASDN list in the production config is checked against, and if necessary
    supplies, the ASDN rows.
    """

    path = Path(path)
    table = pd.read_csv(path, sep="\t")
    required = {"gene_symbol", "gene_set"}
    missing = required - set(table)
    if missing:
        raise ValueError(f"{path} lacks columns: {sorted(missing)}")
    table = table.copy()
    if "final_for_testing" in table:
        table = table[table["final_for_testing"].map(_as_bool)]
    if "status" in table:
        table = table[table["status"].astype(str).eq("defined")]
    table["gene_symbol"] = table["gene_symbol"].astype(str).str.strip()
    table["gene_set"] = table["gene_set"].astype(str).str.strip()
    table = table[
        table["gene_symbol"].ne("")
        & table["gene_set"].ne("")
        & table["gene_symbol"].ne("nan")
    ].drop_duplicates(["gene_set", "gene_symbol"])

    config_asdn = set(map(str, cfg.get("asdn_gene_set", {}).get("genes", [])))
    file_asdn = set(table.loc[table["gene_set"].eq("ASDN"), "gene_symbol"])
    if file_asdn and config_asdn and file_asdn != config_asdn:
        raise ValueError(
            "Frozen ASDN membership differs between config and gene-set table: "
            f"only_config={sorted(config_asdn - file_asdn)}, "
            f"only_table={sorted(file_asdn - config_asdn)}"
        )
    if config_asdn and not file_asdn:
        extra = pd.DataFrame(
            {
                "gene_symbol": sorted(config_asdn),
                "gene_set": "ASDN",
                "category": "literature_frozen",
                "definition_source": "production_config",
                "status": "defined",
                "final_for_testing": True,
            }
        )
        table = pd.concat([table, extra], ignore_index=True)
    sets = {
        str(name): set(part["gene_symbol"].astype(str))
        for name, part in table.groupby("gene_set", sort=True)
    }
    return sets, table


def load_broad_expression_genes(
    gene_set_path: str | Path,
    *,
    flag_column: str = "broadly_expressed",
) -> set[str]:
    """Load one explicitly named reference-only expression flag."""

    path = Path(gene_set_path).with_name("broad_expression_flags.tsv")
    if not path.exists():
        return set()
    table = pd.read_csv(path, sep="\t")
    if not {"gene_symbol", flag_column} <= set(table):
        raise ValueError(
            f"{path} lacks required broad-expression flag column "
            f"{flag_column!r}"
        )
    return set(
        table.loc[table[flag_column].map(_as_bool), "gene_symbol"].astype(str)
    )


def audit_manual_anchor_exclusion(
    provenance_path: str | Path,
    cfg: Mapping[str, Any],
) -> tuple[dict[str, Any], pd.DataFrame]:
    """Verify the strict phosphoform exclusion against Stage-0 provenance.

    The strict analysis already removes the parent genes Slc12a3 and Stk39
    from both the tested set and its eligible background.  A feature-level
    removal is therefore exactly redundant when every Stage-0-qualified
    canonical anchor belongs to a strict-excluded parent gene.  We verify that
    condition explicitly and fail closed if it is ever false.
    """

    enabled = bool(
        cfg.get("canonical_exclusions", {}).get(
            "strict_remove_manual_anchor_phosphoforms", False
        )
    )
    if not enabled:
        summary = {
            "configured": False,
            "status": "not_configured",
            "n_stage0_qualified_anchor_phosphoforms": 0,
            "n_anchor_parent_genes_outside_strict_exclusion": 0,
            "feature_level_removal_numerically_redundant": True,
        }
        return summary, pd.DataFrame([summary])

    path = Path(provenance_path)
    if not path.exists():
        raise FileNotFoundError(
            "Strict manual-anchor sensitivity was configured, but its Stage-0 "
            f"provenance table is missing: {path}"
        )
    table = pd.read_csv(path, sep="\t")
    required = {
        "gene_symbol",
        "source_sheet",
        "source_excel_row",
        "isolated_canonical_qualified",
    }
    missing = required - set(table)
    if missing:
        raise ValueError(
            f"{path} lacks manual-anchor provenance columns: {sorted(missing)}"
        )
    qualified = table[
        table["isolated_canonical_qualified"].map(_as_bool)
    ].copy()
    qualified["raw_feature_id"] = (
        qualified["source_sheet"].astype(str)
        + ":"
        + qualified["source_excel_row"].astype("Int64").astype(str)
    )
    strict_genes = set(
        map(str, cfg.get("canonical_exclusions", {}).get("strict", []))
    )
    outside = sorted(set(qualified["gene_symbol"].astype(str)) - strict_genes)
    if outside:
        raise RuntimeError(
            "Qualified manual anchor phosphoforms occur on parent genes not "
            f"removed by the strict exclusion: {outside}"
        )
    status = (
        "implemented_no_qualified_anchor_features"
        if qualified.empty
        else "implemented_by_exact_parent_gene_exclusion_equivalence"
    )
    summary = {
        "configured": True,
        "status": status,
        "n_stage0_qualified_anchor_phosphoforms": int(len(qualified)),
        "n_anchor_parent_genes_outside_strict_exclusion": int(len(outside)),
        "feature_level_removal_numerically_redundant": True,
        "equivalence_reason": (
            "Every qualified anchor parent gene is removed from the strict "
            "set test and eligible background before inference."
        ),
    }
    if qualified.empty:
        return summary, pd.DataFrame([summary])
    audit = qualified[
        [
            "gene_symbol",
            "source_sheet",
            "source_excel_row",
            "raw_feature_id",
            "qualification_reason",
        ]
    ].copy()
    for key, value in summary.items():
        audit[key] = value
    return summary, audit


def build_exclusions(cfg: Mapping[str, Any]) -> dict[str, set[str]]:
    """Return baseline plus the frozen nested canonical-axis exclusions."""

    exclusions: dict[str, set[str]] = {"none": set()}
    for name, genes in cfg.get("canonical_exclusions", {}).items():
        if isinstance(genes, list):
            exclusions[str(name)] = set(map(str, genes))
    return exclusions


def _set_membership(
    genes: np.ndarray,
    gene_sets: Mapping[str, set[str]],
    exclusions: set[str],
    minimum_genes: int,
) -> tuple[list[str], np.ndarray, np.ndarray]:
    eligible = ~np.isin(genes, sorted(exclusions))
    names: list[str] = []
    columns: list[np.ndarray] = []
    for name, members in gene_sets.items():
        mask = eligible & np.isin(genes, sorted(members))
        if int(mask.sum()) >= minimum_genes:
            names.append(name)
            columns.append(mask)
    membership = (
        np.column_stack(columns)
        if columns
        else np.empty((len(genes), 0), dtype=bool)
    )
    return names, membership, eligible


def _set_statistics(
    z: np.ndarray,
    membership: np.ndarray,
    eligible: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Return competitive and self-contained mean-Z statistics."""

    n_perm, _ = z.shape
    n_sets = membership.shape[1]
    competitive = np.full((n_perm, n_sets), np.nan)
    self_contained = np.full((n_perm, n_sets), np.nan)
    for j in range(n_sets):
        in_set = membership[:, j]
        background = eligible & ~in_set
        with np.errstate(invalid="ignore"):
            set_mean = np.nanmean(z[:, in_set], axis=1)
            bg_mean = np.nanmean(z[:, background], axis=1)
        self_contained[:, j] = set_mean
        competitive[:, j] = set_mean - bg_mean
    return competitive, self_contained


def _empirical_p(
    null: np.ndarray,
    observed: float,
    *,
    exact: bool,
    include_observed: bool = False,
) -> float:
    finite = np.isfinite(null)
    if not np.isfinite(observed) or not finite.any():
        return float("nan")
    count = int(np.sum(null[finite] >= observed))
    if exact and include_observed:
        return count / int(finite.sum())
    return (count + 1) / (int(finite.sum()) + 1)


def _second_pass_inference(
    data: PreparedPhosphoData,
    design: PermutationDesign,
    layout: GeneLayout,
    calibration: NullCalibration,
    gene_sets: Mapping[str, set[str]],
    exclusions: Mapping[str, set[str]],
    cfg: Mapping[str, Any],
    *,
    chunk_size: int,
    min_per_group: int,
    parent_protein_values: np.ndarray | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    minimum_genes = int(cfg["set_test"]["minimum_observable_genes"])
    primary_family = list(map(str, cfg["set_test"].get("primary_family", [])))
    comparator_family = list(map(str, cfg.get("comparator_sets", [])))
    exact = design.mode == "exact"
    null_rows = design.null_rows

    set_blocks: dict[tuple[str, str, str], np.ndarray] = {}
    set_members: dict[
        tuple[str, str], tuple[list[str], np.ndarray, np.ndarray]
    ] = {}
    loo_counts: dict[tuple[str, str, str, str], int] = {}
    loo_valid: dict[tuple[str, str, str, str], int] = {}
    loo_observed: dict[tuple[str, str, str, str], float] = {}
    gene_exceed = {
        name: np.zeros(len(layout.genes), dtype=np.int64) for name in SCORE_NAMES
    }
    gene_valid = {
        name: np.zeros(len(layout.genes), dtype=np.int64) for name in SCORE_NAMES
    }

    for exclusion_name, excluded in exclusions.items():
        for score_name in SCORE_NAMES:
            required_calibration_count = (
                len(design.labels)
                if design.mode == "exact"
                else len(design.null_rows)
            )
            invalid_genes = set(
                layout.genes[
                    ~np.isfinite(calibration.observed_z[score_name])
                    | (
                        calibration.counts[score_name]
                        != required_calibration_count
                    )
                ].astype(str)
            )
            set_members[(exclusion_name, score_name)] = _set_membership(
                layout.genes,
                gene_sets,
                excluded | invalid_genes,
                minimum_genes,
            )
            names, _, _ = set_members[(exclusion_name, score_name)]
            for test_kind in ("competitive", "self_contained"):
                set_blocks[(exclusion_name, score_name, test_kind)] = np.full(
                    (len(design.labels), len(names)), np.nan, dtype=np.float32
                )

    for slc in _iter_chunks(len(design.labels), chunk_size):
        _, raw_scores = _score_assignment_chunk(
            data,
            layout,
            design.labels[slc],
            min_per_group=min_per_group,
            parent_protein_values=parent_protein_values,
        )
        global_rows = np.arange(slc.start, slc.stop)
        local_null = np.isin(global_rows, null_rows)
        for score_name in SCORE_NAMES:
            z = np.divide(
                raw_scores[score_name] - calibration.means[score_name][None, :],
                calibration.sds[score_name][None, :],
                out=np.full_like(raw_scores[score_name], np.nan),
                where=calibration.sds[score_name][None, :] > 0,
            )
            if local_null.any():
                null_z = z[local_null]
                threshold = calibration.observed_z[score_name][None, :]
                valid = np.isfinite(null_z)
                gene_exceed[score_name] += np.sum(
                    valid & (null_z >= threshold), axis=0
                )
                gene_valid[score_name] += valid.sum(axis=0)

            for exclusion_name in exclusions:
                names, membership, eligible = set_members[
                    (exclusion_name, score_name)
                ]
                if not names:
                    continue
                competitive, self_contained = _set_statistics(
                    z, membership, eligible
                )
                set_blocks[
                    (exclusion_name, score_name, "competitive")
                ][slc] = competitive.astype(np.float32)
                set_blocks[
                    (exclusion_name, score_name, "self_contained")
                ][slc] = self_contained.astype(np.float32)

                if not cfg.get("robustness", {}).get("leave_one_gene_out", False):
                    continue
                observed_z = calibration.observed_z[score_name]
                for j, set_name in enumerate(names):
                    member_idx = np.flatnonzero(membership[:, j])
                    if len(member_idx) <= 1:
                        continue
                    eligible_background = eligible & ~membership[:, j]
                    background_mean = np.nanmean(
                        z[:, eligible_background], axis=1
                    )
                    member_sum = np.nansum(z[:, member_idx], axis=1)
                    member_count = np.isfinite(z[:, member_idx]).sum(axis=1)
                    for gene_idx in member_idx:
                        gene = str(layout.genes[gene_idx])
                        key = (exclusion_name, score_name, set_name, gene)
                        denom = member_count - np.isfinite(z[:, gene_idx])
                        loo_mean = np.divide(
                            member_sum - np.nan_to_num(z[:, gene_idx]),
                            denom,
                            out=np.full(len(z), np.nan),
                            where=denom > 0,
                        )
                        loo_stat = loo_mean - background_mean
                        if design.observed_row in global_rows:
                            local_obs = design.observed_row - slc.start
                            loo_observed[key] = float(loo_stat[local_obs])
                        if local_null.any() and key in loo_observed:
                            vals = loo_stat[local_null]
                            valid = np.isfinite(vals)
                            loo_counts[key] = loo_counts.get(key, 0) + int(
                                np.sum(valid & (vals >= loo_observed[key]))
                            )
                            loo_valid[key] = loo_valid.get(key, 0) + int(valid.sum())

    set_rows: list[dict[str, Any]] = []
    for exclusion_name in exclusions:
        for score_name in SCORE_NAMES:
            names, membership, eligible = set_members[
                (exclusion_name, score_name)
            ]
            for test_kind in ("competitive", "self_contained"):
                matrix = set_blocks[(exclusion_name, score_name, test_kind)]
                observed = matrix[design.observed_row].astype(float)
                if exact:
                    null_matrix = matrix.astype(float)
                else:
                    null_matrix = matrix[null_rows].astype(float)
                for j, set_name in enumerate(names):
                    null = null_matrix[:, j]
                    finite = null[np.isfinite(null)]
                    set_rows.append(
                        {
                            "profile": data.profile.name,
                            "exclusion": exclusion_name,
                            "gene_score": score_name,
                            "set_test": test_kind,
                            "gene_set": set_name,
                            "set_role": (
                                "primary"
                                if set_name in primary_family
                                else "kidney_comparator"
                                if set_name in comparator_family
                                else "other"
                            ),
                            "n_observable_genes": int(membership[:, j].sum()),
                            "n_eligible_background_genes": int(
                                (eligible & ~membership[:, j]).sum()
                            ),
                            "observed_statistic": float(observed[j]),
                            "null_mean": (
                                float(np.mean(finite)) if finite.size else np.nan
                            ),
                            "null_sd": (
                                float(np.std(finite, ddof=0))
                                if finite.size
                                else np.nan
                            ),
                            "null_ci_low": (
                                float(np.quantile(finite, 0.025))
                                if finite.size
                                else np.nan
                            ),
                            "null_ci_high": (
                                float(np.quantile(finite, 0.975))
                                if finite.size
                                else np.nan
                            ),
                            "empirical_p_greater": _empirical_p(
                                null,
                                observed[j],
                                exact=exact,
                                include_observed=exact,
                            ),
                            "empirical_p_less": _empirical_p(
                                -null,
                                -observed[j],
                                exact=exact,
                                include_observed=exact,
                            ),
                            "n_null_valid": int(np.isfinite(null).sum()),
                        }
                    )
    set_results = pd.DataFrame(set_rows)

    # Multiplicity is applied within the frozen score/profile/exclusion/test
    # family.  maxT is only the declared primary-family correction.
    set_results["maxT_fwer"] = np.nan
    set_results["minT_fwer"] = np.nan
    set_results["max_absT_fwer"] = np.nan
    set_results["comparator_bh_q"] = np.nan
    group_cols = ["profile", "exclusion", "gene_score", "set_test"]
    for _, idx in set_results.groupby(group_cols, sort=False).groups.items():
        group = set_results.loc[idx]
        primary = group[group["gene_set"].isin(primary_family)]
        if len(primary):
            key = (
                primary.iloc[0]["exclusion"],
                primary.iloc[0]["gene_score"],
                primary.iloc[0]["set_test"],
            )
            names = set_members[(key[0], key[1])][0]
            columns = [names.index(name) for name in primary["gene_set"]]
            matrix = set_blocks[key][:, columns].astype(float)
            null_matrix = matrix if exact else matrix[null_rows]
            max_null = np.nanmax(null_matrix, axis=1)
            min_null = np.nanmin(null_matrix, axis=1)
            max_abs_null = np.nanmax(np.abs(null_matrix), axis=1)
            for row_idx, observed in zip(
                primary.index, primary["observed_statistic"].astype(float)
            ):
                set_results.loc[row_idx, "maxT_fwer"] = _empirical_p(
                    max_null,
                    observed,
                    exact=exact,
                    include_observed=exact,
                )
                set_results.loc[row_idx, "minT_fwer"] = _empirical_p(
                    -min_null,
                    -observed,
                    exact=exact,
                    include_observed=exact,
                )
                set_results.loc[row_idx, "max_absT_fwer"] = _empirical_p(
                    max_abs_null,
                    abs(observed),
                    exact=exact,
                    include_observed=exact,
                )
        comparator = group[group["gene_set"].isin(comparator_family)]
        if len(comparator):
            set_results.loc[
                comparator.index, "comparator_bh_q"
            ] = bh_fdr(comparator["empirical_p_greater"])

    gene_rows: list[dict[str, Any]] = []
    n_sites = (
        data.site_metadata.groupby("gene_symbol").size().reindex(layout.genes).fillna(0)
    )
    mean_intensity = (
        data.site_metadata.groupby("gene_symbol")["mean_log2_signal_uncentered"]
        .median()
        .reindex(layout.genes)
    )
    missingness = (
        data.site_metadata.groupby("gene_symbol")["missing_fraction"]
        .mean()
        .reindex(layout.genes)
    )
    for score_name in SCORE_NAMES:
        required_calibration_count = (
            len(design.labels)
            if design.mode == "exact"
            else len(design.null_rows)
        )
        for i, gene in enumerate(layout.genes):
            gene_rows.append(
                {
                    "profile": data.profile.name,
                    "gene_symbol": gene,
                    "gene_score": score_name,
                    "observed_raw_score": calibration.observed_raw[score_name][i],
                    "null_mean": calibration.means[score_name][i],
                    "null_sd": calibration.sds[score_name][i],
                    "observed_gene_z": calibration.observed_z[score_name][i],
                    "empirical_p_greater": (
                        (gene_exceed[score_name][i] + 1)
                        / (gene_valid[score_name][i] + 1)
                        if gene_valid[score_name][i] > 0
                        else np.nan
                    ),
                    "n_null_valid": gene_valid[score_name][i],
                    "n_sites": int(n_sites.iloc[i]),
                    "median_log2_signal": mean_intensity.iloc[i],
                    "mean_missing_fraction": missingness.iloc[i],
                    "fixed_null_universe_eligible": bool(
                        np.isfinite(calibration.observed_z[score_name][i])
                        and calibration.counts[score_name][i]
                        == required_calibration_count
                    ),
                }
            )
    gene_results = pd.DataFrame(gene_rows)

    loo_rows: list[dict[str, Any]] = []
    for key, observed in loo_observed.items():
        exclusion_name, score_name, set_name, gene = key
        valid = loo_valid.get(key, 0)
        count = loo_counts.get(key, 0)
        loo_rows.append(
            {
                "profile": data.profile.name,
                "exclusion": exclusion_name,
                "gene_score": score_name,
                "gene_set": set_name,
                "removed_gene": gene,
                "observed_competitive_statistic": observed,
                "empirical_p_greater": (
                    (count + 1) / (valid + 1) if valid else np.nan
                ),
                "n_null_valid": valid,
            }
        )
    return set_results, gene_results, pd.DataFrame(loo_rows)


def _safe_qcut(values: pd.Series, q: int, prefix: str) -> pd.Series:
    values = pd.to_numeric(values, errors="coerce")
    fill = values.fillna(values.median())
    if fill.nunique() < 2:
        return pd.Series(prefix + "0", index=values.index)
    bins = pd.qcut(
        fill.rank(method="first"),
        q=min(q, int(fill.nunique())),
        labels=False,
        duplicates="drop",
    )
    return prefix + bins.astype("Int64").astype(str)


def matched_observability_tests(
    gene_results: pd.DataFrame,
    gene_sets: Mapping[str, set[str]],
    exclusions: Mapping[str, set[str]],
    cfg: Mapping[str, Any],
    *,
    n_draws: int,
    seed: int,
) -> pd.DataFrame:
    """Secondary annotation-label null matched on observability.

    This does not replace the animal-label permutation.  It asks whether a
    frozen set is unusual among genes with similar site count, intensity, and
    missingness, using the observed gene-specific Z values.
    """

    rows: list[dict[str, Any]] = []
    rng = np.random.default_rng(seed)
    primary_family = set(map(str, cfg["set_test"].get("primary_family", [])))
    comparator_family = set(map(str, cfg.get("comparator_sets", [])))
    minimum = int(cfg["set_test"]["minimum_observable_genes"])
    scope = cfg.get("matched_observability", {})
    scoped_profiles = set(map(str, scope.get("profiles", [])))
    scoped_scores = set(map(str, scope.get("gene_scores", [])))
    scoped_exclusions = set(map(str, scope.get("exclusions", [])))
    scoped_sets = set(map(str, scope.get("gene_sets", [])))
    for (profile, score_name), frame in gene_results.groupby(
        ["profile", "gene_score"], sort=False
    ):
        if scoped_profiles and str(profile) not in scoped_profiles:
            continue
        if scoped_scores and str(score_name) not in scoped_scores:
            continue
        frame = frame[
            frame["fixed_null_universe_eligible"].astype(bool)
        ].dropna(subset=["observed_gene_z"]).reset_index(drop=True)
        frame["stratum"] = (
            _safe_qcut(np.log1p(frame["n_sites"]), 4, "s")
            + "_"
            + _safe_qcut(frame["median_log2_signal"], 4, "i")
            + "_"
            + _safe_qcut(frame["mean_missing_fraction"], 3, "m")
        )
        for exclusion_name, excluded in exclusions.items():
            if scoped_exclusions and str(exclusion_name) not in scoped_exclusions:
                continue
            pool = frame[~frame["gene_symbol"].isin(excluded)].reset_index(drop=True)
            stratum_indices = {
                str(name): np.asarray(idx, dtype=int)
                for name, idx in pool.groupby("stratum").groups.items()
            }
            for set_name, members in gene_sets.items():
                if scoped_sets and str(set_name) not in scoped_sets:
                    continue
                target = pool["gene_symbol"].isin(members)
                if int(target.sum()) < minimum:
                    continue
                target_counts = pool.loc[target, "stratum"].value_counts()
                observed = float(pool.loc[target, "observed_gene_z"].mean())
                null = np.full(n_draws, np.nan)
                for draw in range(n_draws):
                    picks: list[int] = []
                    valid = True
                    for stratum, count in target_counts.items():
                        available = stratum_indices.get(str(stratum), np.array([], int))
                        if len(available) < int(count):
                            valid = False
                            break
                        picks.extend(
                            rng.choice(available, size=int(count), replace=False).tolist()
                        )
                    if valid and picks:
                        null[draw] = float(
                            pool.iloc[picks]["observed_gene_z"].mean()
                        )
                finite = null[np.isfinite(null)]
                rows.append(
                    {
                        "profile": profile,
                        "exclusion": exclusion_name,
                        "gene_score": score_name,
                        "gene_set": set_name,
                        "set_role": (
                            "primary"
                            if set_name in primary_family
                            else "kidney_comparator"
                            if set_name in comparator_family
                            else "other"
                        ),
                        "n_observable_genes": int(target.sum()),
                        "n_draws": int(finite.size),
                        "observed_self_contained_mean_z": observed,
                        "null_mean": (
                            float(finite.mean()) if finite.size else np.nan
                        ),
                        "null_ci_low": (
                            float(np.quantile(finite, 0.025))
                            if finite.size
                            else np.nan
                        ),
                        "null_ci_high": (
                            float(np.quantile(finite, 0.975))
                            if finite.size
                            else np.nan
                        ),
                        "empirical_p_greater": _empirical_p(
                            finite, observed, exact=False
                        ),
                        "null_type": (
                            "gene_annotation_permutation_matched_on_site_count_"
                            "intensity_missingness"
                        ),
                    }
                )
    return pd.DataFrame(rows)


def _claim_gate_table(
    set_results: pd.DataFrame,
    loo_results: pd.DataFrame,
    cfg: Mapping[str, Any],
    *,
    observable_counts: Mapping[str, int] | None = None,
    promotion_context: Mapping[str, Any] | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Evaluate every frozen claim gate and assign a conservative claim tier."""

    alpha = float(cfg["claim_gates"]["alpha"])
    minimum = int(cfg["set_test"]["minimum_observable_genes"])
    primary_sets = list(map(str, cfg["set_test"].get("primary_family", [])))
    observable_counts = dict(observable_counts or {})
    promotion_context = dict(promotion_context or {})
    comparator_names = set(map(str, cfg.get("comparator_sets", [])))
    distal_related = {
        "DCT1",
        "DCT1_core",
        "DCT2_CNT_transition",
        "DCT2_CNT_external_validation",
        "strict_DCT2_peaked",
        "principal_cell",
        "intercalated_cell",
    }

    def one_row(
        set_name: str,
        *,
        profile: str = "primary",
        exclusion: str = "primary",
    ) -> pd.Series | None:
        match = set_results[
            set_results["profile"].eq(profile)
            & set_results["exclusion"].eq(exclusion)
            & set_results["gene_score"].eq(PRIMARY_SCORE)
            & set_results["set_test"].eq("competitive")
            & set_results["gene_set"].eq(set_name)
        ]
        return match.iloc[0] if len(match) == 1 else None

    def status(value: bool | None) -> str:
        if value is None:
            return "non_evaluable"
        return "pass" if bool(value) else "fail"

    rows: list[dict[str, Any]] = []
    claim_status: dict[str, str] = {}
    for set_name in primary_sets:
        row = one_row(set_name)
        observed_count = (
            int(row["n_observable_genes"])
            if row is not None
            else observable_counts.get(set_name)
        )
        minimum_ok = (
            bool(observed_count >= minimum)
            if observed_count is not None
            else None
        )
        positive_ok = (
            bool(row["observed_statistic"] > 0) if row is not None else None
        )
        max_t_ok = (
            bool(np.isfinite(row["maxT_fwer"]) and row["maxT_fwer"] <= alpha)
            if row is not None
            else None
        )
        required_loo_columns = {
            "profile",
            "exclusion",
            "gene_score",
            "gene_set",
            "removed_gene",
            "observed_competitive_statistic",
        }
        if required_loo_columns <= set(loo_results):
            loo = loo_results[
                loo_results["profile"].eq("primary")
                & loo_results["exclusion"].eq("primary")
                & loo_results["gene_score"].eq(PRIMARY_SCORE)
                & loo_results["gene_set"].eq(set_name)
            ]
        else:
            loo = pd.DataFrame(columns=sorted(required_loo_columns))
        expected_loo = observed_count
        loo_complete: bool | None = (
            bool(
                expected_loo is not None
                and len(loo) == int(expected_loo)
                and loo["removed_gene"].nunique() == int(expected_loo)
            )
            if row is not None
            else None
        )
        loo_ok: bool | None = (
            bool(
                loo_complete
                and (loo["observed_competitive_statistic"] > 0).all()
            )
            if loo_complete is not None
            else None
        )

        uncentered = one_row(
            set_name, profile="official_scaled_uncentered", exclusion="primary"
        )
        summed = one_row(
            set_name, profile="signal_to_noise_sum_centered", exclusion="primary"
        )
        require_normalization = cfg.get("robustness", {}).get(
            "require_normalization_direction_concordance", False
        )
        uncentered_ok: bool | None = (
            bool(
                row is not None
                and uncentered is not None
                and np.sign(row["observed_statistic"])
                == np.sign(uncentered["observed_statistic"])
                and uncentered["observed_statistic"] > 0
            )
            if require_normalization
            else True
        )
        summed_ok: bool | None = (
            bool(
                row is not None
                and summed is not None
                and np.sign(row["observed_statistic"])
                == np.sign(summed["observed_statistic"])
                and summed["observed_statistic"] > 0
            )
            if require_normalization
            else True
        )
        if require_normalization and (row is None or uncentered is None):
            uncentered_ok = None
        if require_normalization and (row is None or summed is None):
            summed_ok = None
        normalization_ok: bool | None = (
            bool(uncentered_ok and summed_ok)
            if uncentered_ok is not None and summed_ok is not None
            else None
        )

        broad = one_row(
            set_name,
            profile="exclude_multicompartment_broad_expression",
            exclusion="primary",
        )
        broad_ok: bool | None = (
            bool(broad["observed_statistic"] > 0)
            if broad is not None
            else None
        )
        if not cfg.get("robustness", {}).get("broad_expression_exclusion", False):
            broad_ok = True

        strict = one_row(set_name, profile="primary", exclusion="strict")
        strict_ok: bool | None = (
            bool(strict["observed_statistic"] > 0)
            if strict is not None
            else None
        )

        external_name = "DCT2_CNT_external_validation"
        external = one_row(
            external_name, profile="primary", exclusion="primary"
        )
        if set_name == "DCT2_CNT_transition":
            external_ok: bool | None = (
                bool(
                    external["n_observable_genes"] >= minimum
                    and external["observed_statistic"] > 0
                )
                if external is not None
                else None
            )
        else:
            external_ok = True

        unrelated = set_results[
            set_results["profile"].eq("primary")
            & set_results["exclusion"].eq("primary")
            & set_results["gene_score"].eq(PRIMARY_SCORE)
            & set_results["set_test"].eq("competitive")
            & set_results["gene_set"].isin(comparator_names - distal_related)
        ].copy()
        if row is None or unrelated.empty:
            comparator_ok: bool | None = None
            strongest_name = None
            strongest_value = np.nan
        else:
            strongest_idx = unrelated["observed_statistic"].astype(float).idxmax()
            strongest_name = unrelated.loc[strongest_idx, "gene_set"]
            strongest_value = float(
                unrelated.loc[strongest_idx, "observed_statistic"]
            )
            comparator_ok = bool(row["observed_statistic"] > strongest_value)

        gate_values: list[bool | None] = [
            minimum_ok,
            positive_ok,
            max_t_ok,
            loo_ok,
            normalization_ok,
            broad_ok,
            strict_ok,
            comparator_ok,
        ]
        if set_name == "DCT2_CNT_transition":
            gate_values.append(external_ok)
        if any(value is None for value in gate_values):
            overall = "non_evaluable"
        elif all(bool(value) for value in gate_values):
            overall = "pass"
        else:
            overall = "fail"
        claim_status[set_name] = overall
        rows.append(
            {
                "gene_set": set_name,
                "n_observable_genes": (
                    int(observed_count)
                    if observed_count is not None
                    else np.nan
                ),
                "gate_minimum_observable_genes": status(minimum_ok),
                "gate_positive_competitive_effect": status(positive_ok),
                "gate_primary_family_maxT": status(max_t_ok),
                "n_leave_one_gene_out_rows": int(len(loo)),
                "gate_leave_one_gene_out_completeness": status(loo_complete),
                "gate_all_leave_one_gene_out_positive": status(loo_ok),
                "gate_centered_vs_uncentered_direction": status(uncentered_ok),
                "gate_scaled_vs_summed_direction": status(summed_ok),
                "gate_normalization_direction_concordance": status(
                    normalization_ok
                ),
                "gate_multicompartment_broad_expression_exclusion_direction": (
                    status(broad_ok)
                ),
                "gate_strict_canonical_exclusion_direction": status(strict_ok),
                "gate_independent_reference_direction": status(external_ok),
                "independent_reference_gene_set": (
                    external_name
                    if set_name == "DCT2_CNT_transition"
                    else "not_applicable"
                ),
                "gate_no_unrelated_compartment_equal_or_stronger": status(
                    comparator_ok
                ),
                "strongest_unrelated_comparator": strongest_name,
                "strongest_unrelated_competitive_statistic": strongest_value,
                "claim_gate_status": overall,
                "alpha": alpha,
                "boundary": (
                    "Parent-protein annotation enrichment in whole-kidney "
                    "phosphoproteomics; not cell-of-origin localization."
                ),
            }
        )
    dct2 = claim_status.get("DCT2_CNT_transition", "non_evaluable")
    asdn = claim_status.get("ASDN", "non_evaluable")
    if dct2 == "pass":
        tier = "DCT2_CNT"
        rationale = "DCT2/CNT transition passed every frozen claim gate."
    elif asdn == "pass":
        tier = "ASDN_only"
        rationale = (
            "ASDN passed every applicable gate; a DCT2/CNT title is not "
            "permitted."
        )
    elif dct2 == "non_evaluable" and asdn == "fail":
        tier = "neither"
        rationale = (
            "DCT2/CNT was non-evaluable at the frozen coverage threshold and "
            "ASDN failed at least one claim gate; no beyond-axis claim is "
            "supported. This does not establish a null DCT2/CNT effect."
        )
    elif asdn == "non_evaluable" and dct2 == "fail":
        tier = "neither"
        rationale = (
            "ASDN was non-evaluable at the frozen coverage threshold and "
            "DCT2/CNT failed at least one claim gate; no beyond-axis claim is "
            "supported."
        )
    elif dct2 == "non_evaluable" and asdn == "non_evaluable":
        tier = "non_evaluable"
        rationale = (
            "Both primary programs were non-evaluable under the frozen claim "
            "gates; absence of a passing tier is not evidence of a null."
        )
    else:
        tier = "neither"
        rationale = "Neither primary set passed every frozen claim gate."

    statistical_dct2 = tier == "DCT2_CNT"
    statistical_asdn = tier in {"DCT2_CNT", "ASDN_only"}
    publication_blockers: list[str] = []
    if bool(cfg.get("contrast", {}).get("condition_reporter_position_confounded")):
        publication_blockers.append(
            "condition is perfectly aliased with reporter-tag position blocks"
        )
    canonical_required = bool(
        cfg.get("publication_promotion_gate", {}).get(
            "qualified_canonical_anchor_required_for_extension_claim", False
        )
    )
    qualified_anchor_count = int(
        promotion_context.get("n_stage0_qualified_anchor_phosphoforms", 0)
    )
    if canonical_required and qualified_anchor_count < 1:
        publication_blockers.append(
            "no isolated Stage-0-qualified canonical NCC/SPAK phosphoform"
        )
    publication_design_ok = not publication_blockers
    publication_status = (
        "blocked_by_design_or_provenance"
        if publication_blockers
        else "statistically_eligible"
        if statistical_asdn
        else "not_statistically_eligible"
    )
    tier_table = pd.DataFrame(
        [
            {
                "claim_tier": tier,
                "DCT2_CNT_gate_status": dct2,
                "ASDN_gate_status": asdn,
                "statistical_beyond_axis_support": statistical_asdn,
                "statistical_dct2_title_eligible": statistical_dct2,
                "statistical_asdn_claim_eligible": statistical_asdn,
                "publication_promotion_status": publication_status,
                "publication_design_and_provenance_gate": (
                    "pass" if publication_design_ok else "fail"
                ),
                "publication_blockers": "; ".join(publication_blockers),
                "dct2_title_permitted": (
                    statistical_dct2 and publication_design_ok
                ),
                "asdn_beyond_axis_claim_permitted": (
                    statistical_asdn and publication_design_ok
                ),
                "publication_beyond_axis_claim_permitted": (
                    statistical_asdn and publication_design_ok
                ),
                "n_stage0_qualified_anchor_phosphoforms": (
                    qualified_anchor_count
                ),
                "rationale": rationale,
            }
        ]
    )
    return pd.DataFrame(rows), tier_table


def run_inference(
    *,
    config_path: str | Path,
    output_dir: str | Path,
    smoke: bool = False,
    profiles: Sequence[str] | None = None,
    n_null_override: int | None = None,
    matched_draws: int | None = None,
) -> dict[str, Any]:
    """Execute the configured full-pipeline inference and write artifacts."""

    config_path = Path(config_path)
    cfg = load_analysis_config(config_path)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    workbook = _resolve_input_path(cfg["input"]["workbook"], config_path)
    protein_workbook = _resolve_input_path(
        cfg["input"]["protein_workbook"], config_path
    )
    gene_set_path = _resolve_input_path(cfg["input"]["gene_sets"], config_path)
    stage0_anchor_path = _resolve_input_path(
        cfg["input"]["stage0_phosphoform_provenance"], config_path
    )
    if not workbook.exists():
        raise FileNotFoundError(f"Missing phosphoproteomics workbook: {workbook}")
    if not gene_set_path.exists():
        raise FileNotFoundError(
            f"Missing frozen gene-set table: {gene_set_path}. "
            "Run the flight-blind subtype-reference builder first."
        )
    gene_sets, gene_set_table = load_frozen_gene_sets(gene_set_path, cfg)
    requested = set(cfg["set_test"].get("primary_family", [])) | set(
        cfg.get("comparator_sets", [])
    )
    missing_sets = requested - set(gene_sets)
    if missing_sets:
        raise ValueError(
            f"Frozen gene-set table lacks configured testing sets: {sorted(missing_sets)}"
        )
    broad_path = gene_set_path.with_name("broad_expression_flags.tsv")
    analysis_profiles = build_analysis_profiles(cfg, include_sensitivities=True)
    if profiles:
        selected = set(profiles)
        analysis_profiles = [p for p in analysis_profiles if p.name in selected]
        unknown = selected - {p.name for p in analysis_profiles}
        if unknown:
            raise ValueError(f"Unknown requested analysis profiles: {sorted(unknown)}")
    if smoke:
        analysis_profiles = analysis_profiles[:]
    required_broad_flags = {
        str(profile.broad_expression_flag_column)
        for profile in analysis_profiles
        if profile.exclude_broad_genes and profile.broad_expression_flag_column
    }
    if required_broad_flags and not broad_path.exists():
        raise FileNotFoundError(
            "Expression-exclusion robustness was configured but its "
            f"reference-only flag table is missing: {broad_path}"
        )
    broad_gene_sets = {
        flag: load_broad_expression_genes(
            gene_set_path, flag_column=flag
        )
        for flag in sorted(required_broad_flags)
    }

    permutation_cfg = cfg["permutation"]
    mode = "smoke" if smoke else str(permutation_cfg["mode"])
    n_null = (
        31
        if smoke
        else n_null_override
        if n_null_override is not None
        else permutation_cfg.get("n_null")
    )
    seed = int(permutation_cfg["seed_for_ordering_only"])
    chunk_size = 16 if smoke else int(permutation_cfg["chunk_size"])
    min_per_group = int(
        cfg["site_model"]["minimum_finite_per_permuted_group_within_plex"]
    )
    normalization_audit = normalization_equivalence_audit(
        workbook,
        cfg["site_filter"]["primary_sheets"],
        output_dir,
        min_per_group=min_per_group,
    )
    exclusions = build_exclusions(cfg)
    manual_anchor_status, manual_anchor_audit = audit_manual_anchor_exclusion(
        stage0_anchor_path, cfg
    )
    all_set: list[pd.DataFrame] = []
    all_gene: list[pd.DataFrame] = []
    all_loo: list[pd.DataFrame] = []
    all_audit: list[pd.DataFrame] = []
    all_validity: list[pd.DataFrame] = []
    attrition_rows: list[dict[str, Any]] = []
    design: PermutationDesign | None = None
    phospho_raw_cache: dict[
        tuple[tuple[str, ...], str],
        tuple[pd.DataFrame, np.ndarray, pd.DataFrame],
    ] = {}

    for profile in analysis_profiles:
        sheets = list(cfg["site_filter"]["primary_sheets"])
        if (
            profile.include_composite
            and "siteQuant_360_compositeSite" not in sheets
        ):
            sheets.append("siteQuant_360_compositeSite")
        cache_key = (tuple(sheets), profile.signal_source)
        if cache_key not in phospho_raw_cache:
            phospho_raw_cache[cache_key] = _extract_raw_table(
                workbook,
                sheets,
                signal_source=profile.signal_source,
            )
        prepared = prepare_osd462_phosphosites(
            workbook,
            profile,
            primary_sheets=cfg["site_filter"]["primary_sheets"],
            broad_genes=broad_gene_sets.get(
                str(profile.broad_expression_flag_column), set()
            ),
            raw_input=phospho_raw_cache[cache_key],
        )
        if design is None:
            design = enumerate_balanced_labels(
                prepared.sample_metadata,
                mode=mode,
                n_null=n_null,
                seed=seed,
            )
            expected = int(permutation_cfg.get("exact_assignments", design.n_total_possible))
            if design.n_total_possible != expected:
                raise ValueError(
                    "Balanced assignment space differs from frozen config: "
                    f"computed={design.n_total_possible}, configured={expected}"
                )
        layout = build_gene_layout(prepared.site_metadata)
        parent_protein_values = None
        if profile.parent_protein_subtraction:
            if not protein_workbook.exists():
                raise FileNotFoundError(
                    "Parent-protein subtraction was frozen but the protein "
                    f"workbook is missing: {protein_workbook}"
                )
            parent_protein_values = load_parent_protein_values(
                protein_workbook,
                prepared.sample_metadata,
                layout.genes,
                channel_center=True,
            )
        calibration = _first_pass_calibration(
            prepared,
            design,
            layout,
            chunk_size=chunk_size,
            min_per_group=min_per_group,
            parent_protein_values=parent_protein_values,
        )
        set_result, gene_result, loo_result = _second_pass_inference(
            prepared,
            design,
            layout,
            calibration,
            gene_sets,
            exclusions,
            cfg,
            chunk_size=chunk_size,
            min_per_group=min_per_group,
            parent_protein_values=parent_protein_values,
        )
        all_set.append(set_result)
        all_gene.append(gene_result)
        all_loo.append(loo_result)
        all_audit.append(prepared.filter_audit)
        prepared.site_metadata["n_assignments_site_contrast_valid"] = (
            calibration.site_valid_assignment_counts
        )
        prepared.site_metadata["fraction_assignments_site_contrast_valid"] = (
            calibration.site_valid_assignment_counts / len(design.labels)
        )
        prepared.site_metadata.to_csv(
            output_dir / f"site_universe_{profile.name}.tsv",
            sep="\t",
            index=False,
        )
        validity = pd.DataFrame(
            {
                "profile": profile.name,
                "permutation_row": np.arange(len(design.labels)),
                "permutation_id": design.permutation_ids,
                "is_observed": (
                    np.arange(len(design.labels)) == design.observed_row
                ),
                "n_valid_site_contrasts": (
                    calibration.assignment_site_valid_counts
                ),
            }
        )
        for score_name in SCORE_NAMES:
            validity[f"n_valid_genes__{score_name}"] = (
                calibration.assignment_gene_valid_counts[score_name]
            )
            required_count = (
                len(design.labels)
                if design.mode == "exact"
                else len(design.null_rows)
            )
            fixed_gene_mask = (
                np.isfinite(calibration.observed_z[score_name])
                & (calibration.counts[score_name] == required_count)
            )
            attrition_rows.append(
                {
                    "profile": profile.name,
                    "gene_score": score_name,
                    "n_label_blind_sites": int(len(prepared.site_metadata)),
                    "n_sites_valid_all_assignments_run": int(
                        (
                            calibration.site_valid_assignment_counts
                            == len(design.labels)
                        ).sum()
                    ),
                    "n_parent_genes_before_fixed_null_requirement": int(
                        len(layout.genes)
                    ),
                    "n_parent_genes_fixed_null_eligible": int(
                        fixed_gene_mask.sum()
                    ),
                    "n_parent_genes_removed_by_fixed_null_requirement": int(
                        len(layout.genes) - fixed_gene_mask.sum()
                    ),
                    "assignment_scope": design.mode,
                    "n_assignments_run": int(len(design.labels)),
                }
            )
        all_validity.append(validity)

    if design is None:
        raise RuntimeError("No analysis profiles were selected")
    set_results = pd.concat(all_set, ignore_index=True)
    gene_results = pd.concat(all_gene, ignore_index=True)
    loo_results = pd.concat(all_loo, ignore_index=True)
    filter_audit = pd.concat(all_audit, ignore_index=True)
    validity = pd.concat(all_validity, ignore_index=True)
    attrition = pd.DataFrame(attrition_rows)
    n_matched = 100 if smoke else int(matched_draws or 10000)
    matched = (
        matched_observability_tests(
            gene_results,
            gene_sets,
            exclusions,
            cfg,
            n_draws=n_matched,
            seed=seed,
        )
        if cfg.get("robustness", {}).get(
            "matched_observability_annotation_permutation_secondary", False
        )
        else pd.DataFrame()
    )
    primary_gene_frame = gene_results[
        gene_results["profile"].eq("primary")
        & gene_results["gene_score"].eq(PRIMARY_SCORE)
        & gene_results["fixed_null_universe_eligible"].astype(bool)
    ].copy()
    primary_gene_frame = primary_gene_frame[
        ~primary_gene_frame["gene_symbol"].isin(
            exclusions.get("primary", set())
        )
    ]
    coverage_names = set(map(str, cfg["set_test"].get("primary_family", [])))
    coverage_names.add("DCT2_CNT_external_validation")
    observable_counts = {
        set_name: int(
            primary_gene_frame["gene_symbol"].isin(
                gene_sets.get(set_name, set())
            ).sum()
        )
        for set_name in sorted(coverage_names)
    }
    gates, claim_tier = _claim_gate_table(
        set_results,
        loo_results,
        cfg,
        observable_counts=observable_counts,
        promotion_context=manual_anchor_status,
    )

    set_results.to_csv(
        output_dir / "set_level_permutation_inference.tsv", sep="\t", index=False
    )
    gene_results.to_csv(
        output_dir / "parent_gene_null_calibration.tsv", sep="\t", index=False
    )
    loo_results.to_csv(
        output_dir / "leave_one_gene_out.tsv", sep="\t", index=False
    )
    matched.to_csv(
        output_dir / "matched_observability_sensitivity.tsv",
        sep="\t",
        index=False,
    )
    filter_audit.to_csv(
        output_dir / "site_filter_audit.tsv", sep="\t", index=False
    )
    validity.to_csv(
        output_dir / "assignment_validity.tsv", sep="\t", index=False
    )
    attrition.to_csv(
        output_dir / "fixed_universe_attrition.tsv", sep="\t", index=False
    )
    gates.to_csv(output_dir / "claim_gates.tsv", sep="\t", index=False)
    claim_tier.to_csv(output_dir / "claim_tier.tsv", sep="\t", index=False)
    manual_anchor_audit.to_csv(
        output_dir / "manual_anchor_exclusion_audit.tsv",
        sep="\t",
        index=False,
    )
    gene_set_table.to_csv(
        output_dir / "gene_set_membership_frozen_copy.tsv",
        sep="\t",
        index=False,
    )
    pd.DataFrame(
        {
            "permutation_row": np.arange(len(design.labels)),
            "permutation_id": design.permutation_ids,
            "is_observed": np.arange(len(design.labels)) == design.observed_row,
        }
    ).to_csv(output_dir / "permutation_index.tsv", sep="\t", index=False)

    unsupported_sensitivities = []
    manifest = {
        "analysis_id": cfg["analysis"]["id"],
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "git_commit": _git_commit(),
        "config": str(config_path),
        "config_sha256": sha256_file(config_path),
        "inputs": {
            "phosphoproteomics_workbook": str(workbook),
            "phosphoproteomics_workbook_sha256": sha256_file(workbook),
            "frozen_gene_sets": str(gene_set_path),
            "frozen_gene_sets_sha256": sha256_file(gene_set_path),
            "protein_workbook": str(protein_workbook),
            "protein_workbook_sha256": (
                sha256_file(protein_workbook)
                if protein_workbook.exists()
                else None
            ),
            "stage0_phosphoform_provenance": str(stage0_anchor_path),
            "stage0_phosphoform_provenance_sha256": sha256_file(
                stage0_anchor_path
            ),
        },
        "profiles": [asdict(p) for p in analysis_profiles],
        "gene_scores": list(SCORE_NAMES),
        "primary_gene_score": PRIMARY_SCORE,
        "primary_set_statistic": cfg["set_test"]["primary_statistic"],
        "site_estimator": cfg["site_model"]["estimator"],
        "minimum_finite_per_permuted_group_within_plex": min_per_group,
        "set_membership_stabilization": (
            "fixed to genes with finite observed Z and a valid parent-gene "
            "score for every assignment used in null calibration"
        ),
        "permutation": {
            "mode": design.mode,
            "n_assignments_run": int(len(design.labels)),
            "n_total_possible": design.n_total_possible,
            "observed_assignment_included": True,
            "balance_block": cfg["permutation"]["block"],
            "chunk_size": chunk_size,
        },
        "nominal_p_threshold_used_for_primary_membership": False,
        "unsupported_or_deferred_configured_sensitivities": unsupported_sensitivities,
        "configured_sensitivities_status": {
            "deduplicated_multimodified": (
                "implemented"
                if cfg["site_filter"].get(
                    "deduplicated_multimodified_sensitivity", False
                )
                else "not_configured"
            ),
            "strict_manual_anchor_phosphoforms": manual_anchor_status["status"],
            "multicompartment_broad_expression_exclusion": (
                "implemented"
                if cfg.get("robustness", {}).get(
                    "broad_expression_exclusion", False
                )
                else "not_configured"
            ),
            "non_distal_or_broad_expression_exclusion_diagnostic": (
                "implemented"
                if cfg.get("robustness", {}).get(
                    "non_distal_or_broad_expression_exclusion_diagnostic",
                    False,
                )
                else "not_configured"
            ),
            "summed_signal_normalization_direction_gate": (
                "implemented"
                if "log2_signal_to_noise_sum_channel_median_centered"
                in cfg["normalization"].get("sensitivities", [])
                else "not_configured"
            ),
        },
        "manual_anchor_exclusion": manual_anchor_status,
        "observable_primary_set_counts_after_primary_exclusion": (
            observable_counts
        ),
        "normalization_equivalence_audit": normalization_audit,
        "condition_reporter_position_confounded": bool(
            cfg["contrast"].get("condition_reporter_position_confounded", False)
        ),
        "output_boundary": (
            "Gene-set enrichment among parent proteins in whole-kidney "
            "phosphoproteomics; no cell-of-origin localization."
        ),
        "fixed_universe_attrition": attrition.to_dict(orient="records"),
    }
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    summary = {
        "output_dir": str(output_dir),
        "profiles": [p.name for p in analysis_profiles],
        "n_assignments": int(len(design.labels)),
        "n_total_possible": design.n_total_possible,
        "n_gene_sets_tested": int(set_results["gene_set"].nunique()),
        "claim_tier": (
            str(claim_tier.iloc[0]["claim_tier"])
            if len(claim_tier)
            else "non_evaluable"
        ),
        "fixed_universe_attrition_primary_score": attrition[
            attrition["gene_score"].eq(PRIMARY_SCORE)
        ].to_dict(orient="records"),
        "smoke": smoke,
    }
    (output_dir / "run_summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    return summary


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Continuous parent-gene phosphoproteomic enrichment with "
            "within-plex balanced animal-label permutations."
        )
    )
    parser.add_argument("--config", default=str(DEFAULT_CONFIG))
    parser.add_argument("--output-dir", required=True)
    parser.add_argument(
        "--smoke",
        action="store_true",
        help="Run all selected profiles with 31 deterministic null assignments.",
    )
    parser.add_argument(
        "--profile",
        action="append",
        dest="profiles",
        help="Run only this profile (repeatable).",
    )
    parser.add_argument(
        "--n-null",
        type=int,
        help="Override sampled-mode null assignments; ignored in exact mode.",
    )
    parser.add_argument(
        "--matched-draws",
        type=int,
        help="Override secondary matched-observability draws.",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    summary = run_inference(
        config_path=args.config,
        output_dir=args.output_dir,
        smoke=args.smoke,
        profiles=args.profiles,
        n_null_override=args.n_null,
        matched_draws=args.matched_draws,
    )
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
